"""Build the UltraRando apworld.

usage : python tools/build_apworld.py [--no-install]

Source of truth : apworld/ultrarando/
- refreshes apworld/ultrarando/data/rooms.json from data/rooms.json (if it changed),
- writes tools/door_mapping_report.txt (Open World door <-> rhelmot hole mapping, per area),
- regenerates apworld/ultrarando/ID_RANGES.md (item and location IDs),
- zips the folder to apworld/ultrarando.apworld,
- copies the folder to upstream/Archipelago/worlds/ultrarando (for local generation tests).
"""
import argparse
import filecmp
import os
import shutil
import sys
import zipfile
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "apworld", "ultrarando")
OUT = os.path.join(ROOT, "apworld", "ultrarando.apworld")
INSTALL = os.path.join(ROOT, "upstream", "Archipelago", "worlds", "ultrarando")
REPORT = os.path.join(ROOT, "tools", "door_mapping_report.txt")
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc")


def write_report() -> None:
    sys.path.insert(0, SRC)
    from core.static_data import get_data  # pure Python, no Archipelago import
    data = get_data()
    cols = ["doors", "doors_mapped", "doors_special", "geo_unique", "name_hint", "kind_conflict",
            "locked_group", "locked_conflict", "conn_mapped", "conn_locked", "conn_special", "conn_virtual",
            "conn_nongeo"]
    lines = [
        "Open World door <-> rhelmot hole mapping (generated by tools/build_apworld.py)",
        "",
        "doors          : Open World doors of rooms present in rooms.json (direction up/down/left/right)",
        "doors_mapped   : doors tied to a hole -> shuffled by room_shuffle",
        "doors_special  : warp/cutscene doors (kept vanilla, logic only)",
        "geo_unique     : room pairs whose vanilla connection matched exactly one usable vanilla hole pair",
        "name_hint      : room pairs with several connections on one side, ordered by door names (west<east, north<south)",
        "kind_conflict  : pairs whose Open World direction is forbidden by the rhelmot hole kinds -> kept vanilla",
        "locked_group   : pairs kept vanilla (ambiguous or conflicting) -> the two rooms move together",
        "conn_*         : Open World room connections by treatment (mapped = through the layout links)",
        "",
        "area " + " ".join(f"{c:>15}" for c in cols),
    ]
    total = Counter()
    for ak, area in data.areas.items():
        total.update(area.report)
        lines.append(f"{ak:>4} " + " ".join(f"{area.report.get(c, 0):>15}" for c in cols))
    lines.append(" all " + " ".join(f"{total.get(c, 0):>15}" for c in cols))
    pct = 100.0 * total["doors_mapped"] / max(1, total["doors"])
    lines += ["", f"coverage: {total['doors_mapped']}/{total['doors']} doors mapped ({pct:.1f}%)", ""]
    lines.append("Unmapped doors (their room pairs stay vanilla):")
    for ak, area in data.areas.items():
        miss = sorted(f"{r}:{d}" for r, o in area.ow_rooms.items() if r not in area.virtual
                      for d, dd in o.doors.items() if dd["direction"] != "special" and (r, d) not in area.door_hole)
        if miss:
            lines.append(f"  {ak}: " + ", ".join(miss))
    lines += ["", f"Pickups without an Open World location (no check): {', '.join(data.skipped_pickups)}",
              "", f"Locations in the static table: {len(data.locations)}"]
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"report -> {REPORT} ({pct:.1f}% doors mapped)")


ID_DOC_HEAD = """# UltraRando — ID ranges

Generated by `tools/build_apworld.py` (do not edit by hand). Game name: `UltraRando`.

| Range | Use |
|---|---|
| `0xC3D0000`–`0xC3D0FFF` | items |
| `0xC3D1000`–`0xC3DFFFF` | locations |

## Items (fixed, never renumber: only append)

- `0xC3D0000` Strawberry, `0xC3D0001` Raspberry (filler)
- `0xC3D0010`–`0xC3D001F`: movement (Dash, 8 dash directions, Climb, Right Climb, Left Climb, Crouch, Wall Jump, Demo Dash)
- `0xC3D0040`–: interactables, in Open World's `interactable_item_data_table` order

Events (no ID, never sent to the client): `Victory`, the vanilla keys/gems
(`"<chapter> - <key name>"`, e.g. `Celestial Resort A - Huge Mess Key`), the 3A clutter and the Farewell breaker.

## Locations

ID = `0xC3D1000 + index` of the location key in the **sorted** list of every key of the static table
(all rooms of `data/rooms.json` except 8a, whatever the options and the layout). The table only changes when
`data/rooms.json` or `data/openworld_logic.json` change; the mod must always use `slot_data.location_ids`.

Keys (contract): `{area}|{level}|room`, `{area}|{level}|checkpoint`, `{area}|clear`,
`{area}|{level}|{kind}|{entity_id}` with kind = strawberry, key, gem, heart, cassette.

"""


def write_id_doc() -> None:
    sys.path.insert(0, SRC)
    from core.static_data import get_data
    from core.names import STRAWBERRY, RASPBERRY, DASH, DIR_DASHES, CLIMB, R_CLIMB, L_CLIMB, CROUCH, WALL_JUMP, \
        DEMO_DASH, INTERACTABLES
    items = [(0xC3D0000, STRAWBERRY), (0xC3D0001, RASPBERRY)]
    items += [(0xC3D0010 + i, n) for i, n in enumerate([DASH] + DIR_DASHES + [CLIMB, R_CLIMB, L_CLIMB, CROUCH,
                                                                               WALL_JUMP, DEMO_DASH])]
    items += [(0xC3D0040 + i, n) for i, n in enumerate(INTERACTABLES)]
    data = get_data()
    lines = [ID_DOC_HEAD, "### Item table", "", "| ID | Item |", "|---|---|"]
    lines += [f"| `0x{i:X}` | {n} |" for i, n in items]
    lines += ["", f"### Location table ({len(data.locations)} locations)", "", "| ID | Key | Name |", "|---|---|---|"]
    for key in sorted(data.locations):
        s = data.locations[key]
        lines.append(f"| `0x{s.id:X}` | `{key}` | {s.name} |")
    with open(os.path.join(SRC, "ID_RANGES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"ID_RANGES.md: {len(items)} items, {len(data.locations)} locations")


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--no-install", action="store_true")
    a = p.parse_args()

    src_rooms = os.path.join(ROOT, "data", "rooms.json")
    dst_rooms = os.path.join(SRC, "data", "rooms.json")
    if os.path.exists(src_rooms) and (not os.path.exists(dst_rooms) or not filecmp.cmp(src_rooms, dst_rooms, False)):
        shutil.copyfile(src_rooms, dst_rooms)
        print("data/rooms.json copied into the apworld (location IDs may change: check ID_RANGES.md)")

    write_report()
    write_id_doc()

    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for base, dirs, files in os.walk(SRC):
            dirs[:] = [d for d in dirs if d != "__pycache__"]
            for name in sorted(files):
                if name.endswith(".pyc"):
                    continue
                full = os.path.join(base, name)
                z.write(full, os.path.relpath(full, os.path.dirname(SRC)))
    print(f"apworld -> {OUT}")

    if not a.no_install:
        os.makedirs(INSTALL, exist_ok=True)
        for entry in os.listdir(INSTALL):
            path = os.path.join(INSTALL, entry)
            shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)
        shutil.copytree(SRC, INSTALL, ignore=IGNORE, dirs_exist_ok=True)
        print(f"installed -> {INSTALL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
